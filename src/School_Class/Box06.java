package School_Class;

class Box06 {
    int width;
    int height;
    int depth;
    double dwidth;
    double dheight;
    double ddepth;

    public Box06(int w, int h, int d) {
        width = w;
        height = h;
        depth = d;
    }
    public Box06(double w, double h, double d) {
        dwidth = w;
        dheight = h;
        ddepth = d;
    }

}
