package School_Class;

 class Box05 {
     int width;
     int height;
     int depth;

     public Box05() {
         width = 1;
         height = 1;
         depth = 1;
     }
     public Box05(int w) {
         width = w;
         height = 1;
         depth = 1;
     }
     public Box05(int w, int h) {
         width = w;
         height = h;
         depth = 1;
     }
     public Box05(int w, int h, int d) {
         width = w;
         height = h;
         depth = d;
     }
}
